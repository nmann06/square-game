const serverPatterns = {
  zh: [[/^You can send up to (\d+) invites per room\.$/, '每个房间最多可以发送 $1 份邀请。']]
};

const languageNames = { en: 'English', zh: '简体中文' };
const listeners = new Set();
let language = 'en';
let tileColors = { ...defaultTileColors };

function t(key, vars = {}) {
  const value = translations[language][key] ?? translations.en[key];
  if (value === undefined) return key;
  return typeof value === 'function' ? value(vars) : value;
}
function serverMessage(message) {
  const text = String(message ?? '');
  const known = serverMessages[language]?.[text];
  if (known) return known;
  for (const [pattern, replacement] of serverPatterns[language] ?? []) if (pattern.test(text)) return text.replace(pattern, replacement);
  return text;
}
function cardName(card) {
  return t('card.name', { color: t(`card.${card.color}`), shape: t(`card.${card.shape}`), number: card.number });
}
function translatePage(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  // Only markup from the translation table above is ever inserted here.
  for (const node of root.querySelectorAll('[data-i18n-html]')) node.innerHTML = t(node.dataset.i18nHtml);
  for (const [attribute, data] of [['placeholder', 'i18nPlaceholder'], ['aria-label', 'i18nAriaLabel'], ['title', 'i18nTitle']]) {
    for (const node of root.querySelectorAll(`[data-${attribute === 'aria-label' ? 'i18n-aria-label' : `i18n-${attribute}`}]`)) node.setAttribute(attribute, t(node.dataset[data]));
  }
}
function applyTileColors(colors) {
  tileColors = { ...defaultTileColors, ...(colors || {}) };
  for (const [name, value] of Object.entries(tileColors)) document.documentElement.style.setProperty(`--tile-${name}`, value);
}
function applySettings(settings = {}) {
  language = translations[settings.language] ? settings.language : 'en';
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  applyTileColors(settings.tileColors);
  translatePage();
  for (const listener of listeners) listener();
}
const settingsKey = 'square-account-settings';
function rememberSettings(settings) {
  try {
    if (settings) localStorage.setItem(settingsKey, JSON.stringify({ language: settings.language, tileColors: settings.tileColors }));
    else localStorage.removeItem(settingsKey);
  } catch {}
}
function rememberedSettings() {
  try { return localStorage.getItem('square-account-token') ? JSON.parse(localStorage.getItem(settingsKey)) || {} : {}; }
  catch { return {}; }
}

window.SquareI18n = {
  t, serverMessage, cardName, translatePage, applySettings, applyTileColors, rememberSettings, languageNames, defaultTileColors, colourblindTileColors,
  get language() { return language; },
  get tileColors() { return { ...tileColors }; },
  locale() { return language === 'zh' ? 'zh-CN' : undefined; },
  onChange(listener) { listeners.add(listener); }
};
applySettings(rememberedSettings());
